# BASIC OPERATIONS IN DIFFERENT EUCLIDEAN RINGS/DOMAINS

function gcdx5(a::RingElem, b::RingElem)
    R = parent(a)

    # for (a, 0) a valid transformation matrix is simply the identity matrix
    if iszero(b)
        return (zero(R), one(R), zero(R), zero(R), one(R))
    end

    U = identity_matrix(R,2)
    r_new = b
    r_old = a
    while !iszero(r_new)
        q,r = divrem(r_old, r_new)
        U = matrix(R, 2,2, [0 1; 1 -q])*U
        r_old = r_new
        r_new = r
    end

    return (r_old, U[1,1], U[1,2], U[2,1], U[2,2])
end

