function rowdeg(A::MatrixElem, idx::Int)
    if is_zero(A[idx,:])
        error("This is a zero-row. row degree is minus infinity.")
    end
    first_elem = true
    d = 0
    for j in 1:ncols(A)
        if !is_zero(A[idx,j])
            if first_elem
                d = degree(numerator(A[idx, j])) - degree(denominator(A[idx, j]))
                first_elem = false
            else
                d = max(degree(numerator(A[idx, j])) - degree(denominator(A[idx, j])), d)
            end
        end
    end
    return d
    #return maximum([degree(numerator(A[idx, j])) - degree(denominator(A[idx, j])) for j in 1:ncols(A)])
end 

function columndeg(A::MatrixElem, idx::Int)
    if is_zero(A[:,idx])
        error("This is a zero-column. column degree is minus infinity.")
    end
    first_elem = true
    d = 0
    for j in 1:ncols(A)
        if !is_zero(A[idx,j])
            if first_elem
                d = degree(numerator(A[i, idx])) - degree(denominator(A[i, idx]))
                first_elem = false
            else
                d = max(degree(numerator(A[i, idx])) - degree(denominator(A[i, idx])), d)
            end
        end
    end
    return d
    return maximum([degree(numerator(A[i, idx])) - degree(denominator(A[i, idx])) for i in 1:nrows(A)])
end 

function coeff_quo(f::AbstractAlgebra.Generic.RationalFunctionFieldElem{QQFieldElem, QQPolyRingElem}, idx::Int)
    g = numerator(f)
    h = denominator(f)
    d = degree(h)
    if idx + d < 0
        return 0
    else 
        return coeff(g, idx+d)//coeff(h, d)
    end
end

function shifted_popov(A::MatrixElem{T}, a::Vector{Int}, b::Vector{Int}) where {T <: AbstractAlgebra.Generic.RationalFunctionFieldElem{QQFieldElem, QQPolyRingElem}}

    K = parent(A[1,1])
    y = gen(K)
    n = nrows(A)
    m = ncols(A)
    s = m + n
    d = maximum([degree(numerator(A[i,j])) for i in 1:n, j in 1:m])
    #a = zeros(Int, m)

    g = one(K)
    sigma = zeros(Int, n)
    mu = zeros(Int, s)
    gamma_star = [rowdeg(A*diagonal_matrix(K, [y^(b[i]) for i in 1:m]), k) for k in 1:n]
    M = identity_matrix(K, s)
    R = [deepcopy(A) -identity_matrix(K, n)]
    N = d*min(n,m) + maximum(a) - minimum(b)
    nvec = vcat(b + [N for i in 1:m], a)
    L = Int[]

    iter = 0
    while length(L) != m
        println(iter)
        #Initialization of variables
        j = argmax([gamma_star[i]-sigma[i] for i in 1:n])
        #r = [R[j,l](0) for l in 1:s]
        r = [coeff_quo(R[j,l], 0) for l in 1:s]
        Lambda = Int[]
        for l in 1:s
            if !is_zero(r[l])
                push!(Lambda, l)
            end
        end
        pi = 0
        diff = maximum([nvec[l] - mu[l] for l in Lambda])
        for l in Lambda
            if nvec[l] - mu[l] == diff
                pi = l
                break
            end
        end
        p = [coeff_quo(M[l,pi], mu[l]-1) for l in 1:s]

        #Check stopping criterion
        for l in 1:s
            if is_zero(R[:,l]) && !(l in L || l in Lambda) 
                push!(L, l)
            end
        end
        if length(L) == m
            break
        end

        #@infiltrate
        #Increase order for l = 1,...,m , l != pi
        for l in 1:s # oder 1:m?
            #println(string("l = ", l))
            if l == pi
                continue
            end
            M[:,l] = (1//g).*(r[pi].*M[:,l] - r[l].*M[:,pi])
            R[:,l] = (1//g).*(r[pi].*R[:,l] - r[l].*R[:,pi]) 
        end
        #println("Checkpoint 1")
        #@infiltrate
        #Increase order for l = pi and adjust degree constraints
        M[:,pi] = (1//g).*((y*r[pi]).*M[:,pi] - sum(p[l].*M[:,l] for l in 1:s if l != pi))
        R[:,pi] = (1//g).*((y*r[pi]).*R[:,pi] - sum(p[l].*R[:,l] for l in 1:s if l != pi))

        #Adjust residual in row j
        R[:,j] = (1//y).*R[:,j]
        
        #Update variables
        g = r[pi]
        sigma[j] = sigma[j] + 1
        mu[pi] = mu[pi] + 1 

        #Testing overhead
        println(L)
        iter = iter+1

        @infiltrate

        if iter == 100
            error("Zu viele Iterationen...")
        end
    end

    sort!(L)
    r = n+1 - findfirst(>(m), L)
    H = M[(m+1):(m+n), L]
    U = M[1:m, L]

    return (U, L[1:m], H, L[m+1:m+n])
end











