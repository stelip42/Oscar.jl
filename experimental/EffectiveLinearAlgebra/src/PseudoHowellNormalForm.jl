# BASIC OPERATIONS IN QUOTIENT RINGS OVER MAXIMAL ORDERS OF NUMBER FIELDS

function gcdx5(a::Union{AbsSimpleNumFieldOrderQuoRingElem}, b::Union{AbsSimpleNumFieldOrderQuoRingElem})
    QuotS = parent(a)
    S = base_ring(QuotS)
    R = base_ring(S)
    
    # for (a, 0) a valid transformation matrix is simply the identity matrix
    if iszero(b)
        return (zero(QuotS), one(QuotS), zero(QuotS), zero(QuotS), one(QuotS))
    end
    g = gen(lift(a)*S + lift(b)*S, QuotS)
    ann = annihilator(g)
    #println(string("a:", a, ", b:", b, ", g:", g))
    v_0 = div(a,g)
    v = v_0
    #println(string("v:", v))
    it = 0
    while phi(a) != phi(g)*phi(v)
        if it == 8
            #println(string("phi(a): ", phi(a), ", phi(g): ", phi(g), ", phi(v): ", phi(v)))
            error(string("Nach ", it, " Iterationen immernoch kein passendes Elem gefunden."))
        end
        v = v_0 + rand(QuotS)*ann
        it = it+1
        #println(string("ann: ",ann))
    end

    u_0 = div(b,g)
    u = u_0
    #println(string("u:", u))
    while phi(b) != phi(g)*phi(u)
        u = u_0 + rand(QuotS)*ann
    end

    d = degree(S)
    vec = [i == 1 ? one(R) : zero(R) for i in 1:d]
    X = solve([representation_matrix(lift(v)); representation_matrix(lift(u)); basis_matrix(QuotS)], vec)
    s = QuotS(dot(map(S, X[1:d]), basis(S)))
    t = QuotS(dot(map(S, X[d+1:2d]), basis(S)))
    return (g, s, t, -u, v)
end

function annihilator(a::Union{AbsSimpleNumFieldOrderQuoRingElem})
    QuotS = parent(a)
    S = base_ring(QuotS)
    d = degree(S)
    #compute elements x and y such that M_a*x + M_mf*y = 0
    #println([representation_matrix(lift(a)); basis_matrix(QuotS)])
    ker = kernel([representation_matrix(lift(a)); basis_matrix(QuotS)])
    #construct the ideal generated by all solutions x
    #println(ker)
    #println(basis(S))
    ann = ideal(ker[1:d,1:d]*basis(S))
    #use function gen to compute a generator of the ideal ann in S/mf
    return gen(ann, QuotS)
end

function phi(a::Union{AbsSimpleNumFieldOrderQuoRingElem})
    R = parent(a)
    #if iszero(a)
    #    return ZZ(0)
    #end
    U = R.tmp_euc
    d = degree(base_ring(R))

    U[1:d,1:d] = representation_matrix(a.elem)
    U[d+1:2d,1:d] = basis_matrix(R)

    U = hermite_form(U)
    z = ZZ(1)
    for i in 1:d
        mul!(z, z, U[i, i])
    end
    return z
end

function gen(af::NumFieldOrderIdeal, QuotS::AbsSimpleNumFieldOrderQuoRing)
    S = base_ring(QuotS)
    mf = ideal(S, basis_matrix(QuotS))
    bf = af + mf
    s = basis_matrix(mf)[1,1]
    sf_2 = s^2*S
    #Quotbf, hom = quo(bf, sf_2)
    c = rand(bf, Int(min(s^2-1, 2^30)))
    #cf = preimage(hom, c)*R + sf_2
    cf = c*S + sf_2
    while cf != bf
        c = rand(bf, Int(min(s^2-1, 2^30)))
        cf = c*S + sf_2
    end
    #println(string("cf:", cf, ", s:", s, ", af:", af))
    return QuotS(c)
end

function eucdiv(a::Union{AbsSimpleNumFieldOrderQuoRingElem}, b::Union{AbsSimpleNumFieldOrderQuoRingElem})
    QuotS = parent(a)
    (flag,q) = divides(a,b)
    r = zero(QuotS)
    #if b divides a, then return the divisor q and r = 0
    if flag
        return (q,r)
    end
    #test random elements q of R until a = q*b + r is a valid Euclidean division
    while phi(r) >= phi(b)
        q = rand(R)
        r = a-q*b
    end
    return (q,r)
end

















#STRONG ECHELON FORM FOR MATRICES OF DIFFERENT TYPES

function strong_echelon_form_lip(A::MatrixElem{<:RingElem})
    M = deepcopy(A)
    R = parent(A[1,1])
    n = nrows(A)
    m = ncols(A)
    zero_cols = 0

    #step 1) compute upper triangular form of M
    for j in 1:m
        #check if there is a pivot element in column j
        if is_zero(M[j-zero_cols:n,j])
            zero_cols = zero_cols + 1 
            continue
        end
        #calculate the pivot element in column j and do row transformation such that all entries below the pivot are 0
        for i in j+1-zero_cols:n
            (_, s, t, u, v) = gcdx5(M[j-zero_cols,j], M[i,j])
            M[[j-zero_cols,i], 1:m] = matrix(R,2,2,[s t; u v])*M[[j-zero_cols,i], 1:m]
        end
    end

    #step 2) if n <= m augment with m+1-n zero rows
    if n <= m
        M_ = zero_matrix(R, m+1, m)
        M_[1:n,1:m] = M
        M = M_
    end

    #step 3) sort the rows such that condition (1) of a strong echelon form is satisfied.
    for i in 1:m
        #it = 0
        col_pivot = 0
        while col_pivot <= m && col_pivot != i
            col_pivot = i
            #find column index of pivot element in row i
            while col_pivot <= m && iszero(M[i,col_pivot])
                col_pivot = col_pivot + 1
            end
            #if row i is not zero and col_pivot is not i, then swap row i and col_pivot
            if col_pivot <= m && col_pivot != i
                swap_rows!(M,i,col_pivot)
                # it = it+1
                # if it > m+1
                #    error("Beim Zeilen Tauschen passt was nicht...")
                # end
            end
        end
    end

    #step 4) do some linear combinations in order to ensure condition (2) of a strong echelon form. This step is only relevant, if R has zero divisors.
    for j in 1:m
        #duplicate the j-th row into the m+1-th row and multiply the m+1-th row with an annihilator of the pivot element. 
        #if M[j,j] != 0
            M[m+1,1:m] = annihilator(M[j,j]).*M[j,1:m]
        #else
        #    M[m+1,1:m] = M[j,1:m]
        #end
        #Compute row-transformation for euclidean rings with gcdx5 function to linear-combine row m+1 with row j+1, j+2, ..., and row m.
        for i in j+1:m
            (_, s, t, u, v) = gcdx5(M[i,i], M[m+1,i])
            M[[i,m+1], 1:m] = matrix(R,2,2,[s t; u v])*M[[i,m+1], 1:m]
        end
    end
    return M[1:m,1:m]
end

function strong_echelon_form_lip(A::MatrixElem{<:FieldElem})
    m = ncols(A)
    #Compute an echelon form of A
    M = echelon_form(A)
    #Sort the rows such that condition (1) of a strong echelon form is satisfied.
    for i in 1:m
        col_pivot = 0
        while col_pivot <= m && col_pivot != i
            col_pivot = i
            while col_pivot <= m && iszero(M[i,col_pivot])
                col_pivot = col_pivot + 1
            end
            if col_pivot <= m && col_pivot != i
                swap_rows!(M,i,col_pivot)
            end
        end
    end
    return M
end


















# PSEUDO-HNF FOR PSEUDO-MATRICES OVER DEDEKIND DOMAINS

function pseudo_hnf_full_col_rank(P::Hecke.PMat) 
    H = deepcopy(P)
    n = nrows(H)
    m = ncols(H)
    A = matrix(H)
    I = coefficient_ideals(H) 
    S = order(numerator(I[1]))
    R = base_ring(S)
    K = parent(A[1,1])
    d = degree(S)

    #step 0) Adjust the given pseudomatrix such that all entries and ideals are integral.
    c = S(1)
    for i in 1:n
        # first the matrix entries
        for j in 1:m
            denom = denominator(A[i,j])
            if !is_one(denom)
                multiply_row!(A, i, denom)
                c = c*denom
            end
        end
        # then the coefficient ideal
        c = c*denominator(I[i])
    end
    
    #step 1) Map P into PMat_nxm(S/m) and compute a matrix B in Mat_nxm(S/m) with RS(B) = RS(P).

    #find m linear independent rows
    indices = Int[]
    for i in 1:n
        if rank(A[vcat(indices,[i]),:]) > length(indices)
            push!(indices, i)
        end
        if length(indices) == m
            break
        end
    end

    #compute a suitable ideal mf of S
    #@infiltrate
    mf = (S(det(A[indices,:]))*S)*numerator(prod(I))

    #find a matrix B in Mat_nxm(S/m) with RS(B) = RS(P).
    QuotS, proj = quo(S, mf)
    B = matrix(QuotS,n,m,[proj(S(A[i,j])) for i in 1:n for j in 1:m])
    for i in 1:n
        g = gen(numerator(I[i]), QuotS)
        B[i,1:m] = g.*B[i,1:m]
    end


    #step 2) Calculate a strong echelon form C in Mat_mxm(S/m) of B.
    C = strong_echelon_form_lip(B)

    #step 3) Find a pseudomatrix P′ = (D,I) in PMat_2mxm(S) such that D[1:m,1:m] = C and RS(P′) = RS(P).
    D = [map_entries(x -> K(preimage(proj, x)), C); zero_matrix(K, n-m, m)]
    I = [fractional_ideal(S, S*1) for i in 1:n]

    #step 4) Compute a pseudo-HNF H of P′ and conclude, that H is also a pseudo-HNF of P.
    for i in 1:m
        gf = D[i,i]*S + mf
        gf_inv = inv(gf)
        af = simplify((S*D[i,i])*gf_inv)
        bf = simplify(mf*gf_inv)
        
        c = lcm(denominator(af), denominator(bf))
        I[i] = gf
        a, _ = partition_of_one(c*numerator(af),c*numerator(bf))
        #@infiltrate
        D[i,1:m] = (a//D[i,i]).*D[i,1:m]
        D[i,i] = 1
        #@infiltrate
    end

    return pseudo_matrix(D, I)
end

function pseudo_hnf_full_col_rank(P::Hecke.PMat{AbsSimpleNumFieldOrderElem, T}) where T 
    K = number_field(parent(matrix(P)[1,1]))
    A = map(K, matrix(P))
    return pseudo_hnf_full_col_rank(pseudo_matrix(A, coefficient_ideals(P)))
end

function pseudo_hnf_full_col_rank(P::Hecke.PMat{T, AbsSimpleNumFieldOrderIdeal}) where T 
    OK = order(coefficient_ideals(P)[1])
    I = map_entries(x -> fractional_ideal(OK, x), coefficient_ideals(P))
    return pseudo_hnf_full_col_rank(pseudo_matrix(matrix(P), I))
end

function pseudo_hnf_lip(P::Hecke.PMat)
    n = nrows(P)
    m = ncols(P)
    A = matrix(P)
    r = rank(A)
    K = parent(A[1,1])

    #find rank(P) linear independent columns
    indices = Int[]
    for i in 1:m
        if rank(A[:,vcat(indices,[i])]) > length(indices)
            push!(indices, i)
        end
        if length(indices) == r
            break
        end
    end

    A1 = A[:,indices]
    A2 = [A1[1:r,1:r] zero_matrix(K,r,n-r); A1[r+1:n,1:r] identity_matrix(K, n-r)]
    H = pseudo_hnf_full_col_rank(pseudo_matrix(A2, coefficient_ideals(P)))
    U = matrix(H)inv(A2)
    return pseudo_matrix(U*A, coefficient_ideals(H))
end







