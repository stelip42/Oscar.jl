function rowdeg(A::MatrixElem, idx::Int)
    if is_zero(A[idx,:])
        error("This is a zero-row. row degree is minus infinity.")
    end
    first_elem = true
    d = 0
    for j in 1:ncols(A)
        if !is_zero(A[idx,j])
            if first_elem
                d = degree(numerator(A[idx, j])) - degree(denominator(A[idx, j]))
                first_elem = false
            else
                d = max(degree(numerator(A[idx, j])) - degree(denominator(A[idx, j])), d)
            end
        end
    end
    return d
    #return maximum([degree(numerator(A[idx, j])) - degree(denominator(A[idx, j])) for j in 1:ncols(A)])
end 

