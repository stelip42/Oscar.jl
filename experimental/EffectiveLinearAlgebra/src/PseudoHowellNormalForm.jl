# PSEUDO-HNF FOR PSEUDO-MATRICES OVER DEDEKIND DOMAINS

function pseudo_hnf_full_col_rank(P::Hecke.PMat) 
    H = deepcopy(P)
    n = nrows(H)
    m = ncols(H)
    A = matrix(H)
    I = coefficient_ideals(H) 
    S = order(numerator(I[1]))
    R = base_ring(S)
    K = parent(A[1,1])
    d = degree(S)

    #step 0) Adjust the given pseudomatrix such that all entries and ideals are integral.
    c = S(1)
    for i in 1:n
        # first the matrix entries
        for j in 1:m
            denom = denominator(A[i,j])
            if !is_one(denom)
                multiply_row!(A, i, denom)
                c = c*denom
            end
        end
        # then the coefficient ideal
        c = c*denominator(I[i])
    end
    
    #step 1) Map P into PMat_nxm(S/m) and compute a matrix B in Mat_nxm(S/m) with RS(B) = RS(P).

    #find m linear independent rows
    indices = Int[]
    for i in 1:n
        if rank(A[vcat(indices,[i]),:]) > length(indices)
            push!(indices, i)
        end
        if length(indices) == m
            break
        end
    end

    #compute a suitable ideal mf of S
    #@infiltrate
    mf = (S(det(A[indices,:]))*S)*numerator(prod(I))

    #find a matrix B in Mat_nxm(S/m) with RS(B) = RS(P).
    QuotS, proj = quo(S, mf)
    B = matrix(QuotS,n,m,[proj(S(A[i,j])) for i in 1:n for j in 1:m])
    for i in 1:n
        g = gen(numerator(I[i]), QuotS)
        B[i,1:m] = g.*B[i,1:m]
    end


    #step 2) Calculate a strong echelon form C in Mat_mxm(S/m) of B.
    C = strong_echelon_form_lip(B)

    #step 3) Find a pseudomatrix P′ = (D,I) in PMat_2mxm(S) such that D[1:m,1:m] = C and RS(P′) = RS(P).
    D = [map_entries(x -> K(preimage(proj, x)), C); zero_matrix(K, n-m, m)]
    I = [fractional_ideal(S, S*1) for i in 1:n]

    #step 4) Compute a pseudo-HNF H of P′ and conclude, that H is also a pseudo-HNF of P.
    for i in 1:m
        gf = D[i,i]*S + mf
        gf_inv = inv(gf)
        af = simplify((S*D[i,i])*gf_inv)
        bf = simplify(mf*gf_inv)
        
        c = lcm(denominator(af), denominator(bf))
        I[i] = gf
        a, _ = partition_of_one(c*numerator(af),c*numerator(bf))
        #@infiltrate
        D[i,1:m] = (a//D[i,i]).*D[i,1:m]
        D[i,i] = 1
        #@infiltrate
    end

    return pseudo_matrix(D, I)
end

function pseudo_hnf_full_col_rank(P::Hecke.PMat{AbsSimpleNumFieldOrderElem, T}) where T 
    K = number_field(parent(matrix(P)[1,1]))
    A = map(K, matrix(P))
    return pseudo_hnf_full_col_rank(pseudo_matrix(A, coefficient_ideals(P)))
end

function pseudo_hnf_full_col_rank(P::Hecke.PMat{T, AbsSimpleNumFieldOrderIdeal}) where T 
    OK = order(coefficient_ideals(P)[1])
    I = map_entries(x -> fractional_ideal(OK, x), coefficient_ideals(P))
    return pseudo_hnf_full_col_rank(pseudo_matrix(matrix(P), I))
end

function pseudo_hnf_lip(P::Hecke.PMat)
    n = nrows(P)
    m = ncols(P)
    A = matrix(P)
    r = rank(A)
    K = parent(A[1,1])

    #find rank(P) linear independent columns
    indices = Int[]
    for i in 1:m
        if rank(A[:,vcat(indices,[i])]) > length(indices)
            push!(indices, i)
        end
        if length(indices) == r
            break
        end
    end

    A1 = A[:,indices]
    A2 = [A1[1:r,1:r] zero_matrix(K,r,n-r); A1[r+1:n,1:r] identity_matrix(K, n-r)]
    H = pseudo_hnf_full_col_rank(pseudo_matrix(A2, coefficient_ideals(P)))
    U = matrix(H)inv(A2)
    return pseudo_matrix(U*A, coefficient_ideals(H))
end







